import type { Context } from "@deepseek-ai/cordis";
import { createHash } from "node:crypto";
import { FrozenSkills, createSkillPackageSnapshot } from "../../skills/local.js";
import { parseSkillMarkdown, skillName } from "../../skills/markdown.js";
import type { SkillPackageSnapshot, SkillSource } from "../../skills/types.js";
import type { Memory } from "../types.js";
import { memoryFiles } from "../files.js";
import { PluginWorkOwner } from "../../boot/plugin-control/work-owner.js";
import type {} from "../../skills/service.js";

const hash = (value: string) => createHash("sha256").update(value).digest("hex");

/** Adapter only: Memory owns generated bytes; Skills owns discovery, activation and model reads. */
export function createMemorySkillSource(memory: Memory): SkillSource {
  const id = `memory-${hash(memory.libraryId)}`;
  const collect = async (signal?: AbortSignal) => {
    const files = await memoryFiles(memory, signal), packages: SkillPackageSnapshot[] = [], issues: { location: string; message: string }[] = [];
    for (const manifest of files.filter(file => /^skills\/[^/]+\/SKILL\.md$/u.test(file.path ?? ""))) {
      const location = `${memory.libraryId}/${manifest.path}`;
      try {
        const name = skillName(manifest.path!.split("/")[1]), metadata = parseSkillMarkdown(manifest.content, name);
        const prefix = `skills/${name}/`;
        packages.push(createSkillPackageSnapshot({ ...metadata, source: "memory", location,
          packageId: hash(location), digest: hash(manifest.content) },
        Object.fromEntries(files.filter(file => file.path?.startsWith(prefix)).map(file => [file.path!.slice(prefix.length), file.content]))));
      } catch (error) { issues.push({ location, message: error instanceof Error ? error.message : String(error) }); }
    }
    signal?.throwIfAborted();
    return { packages, issues };
  };
  return {
    id,
    async list(input) { const result = await collect(input.signal); return { skills: result.packages.map(pkg => pkg.skill), issues: result.issues }; },
    async read(input) { return new FrozenSkills((await collect(input.signal)).packages).read(input); },
    async snapshot(input) {
      const result = await collect(input.signal);
      if (result.issues.length) throw new Error("Memory Skill packages contain diagnostics");
      return result.packages;
    },
  };
}

export default {
  name: "memory-skills", inject: ["memory", "skills", "launch"],
  apply(ctx: Context) {
    const owner = new PluginWorkOwner(ctx, { code: "memory_skills", codeReload: true });
    const source = createMemorySkillSource(ctx.memory);
    // Profile workers already carry the complete, pinned Skill catalog and user activation.
    const releaseSource = "resourceMode" in ctx.skills ? () => {} : ctx.skills.registerSource({ id: source.id,
      list: input => owner.run(() => source.list(input)), read: input => owner.run(() => source.read(input)),
      snapshot: input => owner.run(() => source.snapshot(input)) });
    const releaseFilter = ctx.memory.registerModelFileFilter((files, signal) => owner.run(async () => {
      const catalog = await ctx.skills.list({ cwd: ctx.launch.cwd, ...(signal ? { signal } : {}) });
      const allowed = new Set(catalog.skills.filter(skill => skill.source === "memory" && skill.enabled !== false && skill.modelInvocable &&
        skill.packageId === hash(JSON.stringify([source.id, hash(`${ctx.memory.libraryId}/skills/${skill.name}/SKILL.md`)]))).map(skill => skill.name));
      return files.filter(file => !file.path?.startsWith("skills/") || allowed.has(file.path.split("/")[1]!));
    }));
    ctx.effect(() => () => { releaseFilter(); releaseSource(); }, "memory.skills.detach");
  },
};
